/** Contenido de la portada: nada inventado ni de desarrollo (decisión del 2026-11-20). */
import { readFileSync } from "node:fs";
import path from "node:path";

import { describe, expect, it } from "vitest";

const leer = (f: string) => readFileSync(path.resolve(import.meta.dirname, "..", f), "utf8");
const portada = leer("app/page.tsx");

describe("portada", () => {
  it("sin métricas ni indicadores inventados", () => {
    for (const falso of ["+1500", "+22k", "Calificación promedio", "+38%", "Negocios activos", "Reservas al mes"]) {
      expect(portada).not.toContain(falso);
    }
  });

  it("sin reseñas ni profesionales ficticios: ni calificaciones ni «Ver perfil»", () => {
    expect(portada).not.toMatch(/rating|Ver perfil|★/);
    for (const nombre of ["Leyva", "Jona", "Crisóstomo", "Carlitos", "Maldonado"]) expect(portada).not.toContain(nombre);
  });

  it("la marca es STYLEHUB y no quedan textos internos de desarrollo", () => {
    expect(portada).not.toMatch(/STYLIFY|New UI Stack|producto SaaS|Responsive y limpia|AI Scheduling|Role-based UX/);
    expect(portada).toContain("¡Conoce STYLEHUB!");
  });

  it("sin la foto que da 404 en Unsplash", () => {
    expect(portada).not.toContain("photo-1599351431408-5a13587f6f3f");
  });

  it("«Más información» para negocios lleva al registro", () => {
    expect(portada).not.toContain("tipo=admin");
    const i = portada.indexOf("Más información");
    expect(portada.lastIndexOf('href="/register"', i)).toBeGreaterThan(portada.lastIndexOf("<Link", i) - 1);
  });

  it("la descripción del sitio es real", () => {
    const layout = leer("app/layout.tsx");
    expect(layout).not.toContain("Generated by");
    expect(layout).toContain("description: DESCRIPCION_SITIO");
  });

  it("las fotos se sirven desde el propio sitio y existen", async () => {
    const { existsSync } = await import("node:fs");
    expect(portada).not.toContain("images.unsplash.com");
    const fotos = [...portada.matchAll(/\/estilos\/([a-z-]+)\.jpg/g)].map((m) => m[1]);
    expect(fotos.length).toBe(6);
    for (const f of fotos) expect(existsSync(path.resolve(import.meta.dirname, "..", `public/estilos/${f}.jpg`))).toBe(true);
  });

  it("las fotos van con next/image (WebP, tamaño según pantalla y carga diferida), no como fondo CSS", () => {
    expect(portada).not.toMatch(/backgroundImage/);
    expect(portada.match(/<Image\s+src=\{item\.foto\}[\s\S]*?sizes=/g)?.length).toBe(1);
    expect(portada.match(/<Image src="\/estilos\/[a-z-]+\.jpg" alt="" fill sizes=/g)?.length).toBe(2);
    // Solo el logo del encabezado carga de inmediato (`priority` está obsoleto en Next 16); el resto es diferido
    expect(portada).not.toMatch(/\bpriority\b|\bpreload\b/);
    expect(portada.match(/loading="eager"/g)?.length).toBe(1);
  });
});
